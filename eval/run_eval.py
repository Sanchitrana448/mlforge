"""Reproducible evaluation. Run: python eval/run_eval.py

Trains with the fixed seed (42, 5,000 rows) and writes RESULTS.md: model
comparison on validation, held-out test metrics, and the operating-point table
(threshold chosen on validation, reported on test).
"""
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import app.train as train  # noqa: E402

train.REGISTRY_DIR = Path(tempfile.mkdtemp())  # do not touch the repo's registry


def main() -> None:
    m = train.train_and_register(n_rows=5000, seed=42)
    t, op = m["test_metrics"], m["operating_point"]
    d, r = op["test_at_default_0.5"], op["test_at_recommended"]
    out = [
        "# Evaluation results", "",
        "Generated by `python eval/run_eval.py`. Seed 42, 5,000 synthetic rows, stratified 70/15/15 split. "
        "Model chosen on validation ROC-AUC; every test number comes from data the selection never saw.", "",
        "## Model comparison (validation)", "",
        "| Model | Accuracy | Precision | Recall | F1 | ROC-AUC |", "|---|---|---|---|---|---|",
    ]
    for c in m["candidates_evaluated"]:
        out.append(f"| {c['model']}{' (selected)' if c['model'] == m['selected_model'] else ''} | {c['accuracy']} | {c['precision']} | {c['recall']} | {c['f1']} | {c['roc_auc']} |")
    out += [
        "", "## Held-out test (selected model, default 0.5 threshold)", "",
        f"accuracy {t['accuracy']} · precision {t['precision']} · recall {t['recall']} · F1 {t['f1']} · ROC-AUC {t['roc_auc']}", "",
        "## Operating point", "",
        f"Assumed costs: retention offer £{op['assumptions']['offer_cost']:.0f} per flagged customer, "
        f"£{op['assumptions']['lost_customer_cost']:.0f} per missed churner. Threshold chosen on the validation set "
        f"({op['recommended_threshold']}), reported on test.", "",
        "| Threshold | Recall | Precision | Customers flagged | Total cost |", "|---|---|---|---|---|",
    ]
    for row in op["test_table"]:
        tag = " (recommended)" if row["threshold"] == op["recommended_threshold"] else " (default)" if row["threshold"] == 0.5 else ""
        out.append(f"| {row['threshold']}{tag} | {row['recall']} | {row['precision']} | {row['flagged']} | £{row['total_cost']:,.0f} |")
    saving = 1 - r["total_cost"] / d["total_cost"]
    out += [
        "", f"At the recommended threshold, recall rises from {d['recall']} to {r['recall']} and total cost falls "
        f"{saving:.0%} (£{d['total_cost']:,.0f} to £{r['total_cost']:,.0f}) on the test set.", "",
        "## Reading these numbers honestly", "",
        f"- The recommended threshold flags {r['flagged']} of the {sum(map(sum, t['confusion_matrix']))} test customers. At a 10:1 cost ratio "
        "the cheapest policy is to contact most of the base. That is what the assumptions imply, not necessarily "
        "what a business would accept.",
        "- The cost model assumes every retention offer works. Real offers save only some customers, which pushes "
        "the best threshold up.",
        "- The data is synthetic with a known generating process, so absolute scores say little about production data.", "",
    ]
    (ROOT / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
